/**
 * Small seeded random number generator (mulberry32). Procedural layouts use it instead of
 * Math.random so a scene looks the same on every device and every visit, and so the layout can
 * be checked by `npm run check`.
 */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
